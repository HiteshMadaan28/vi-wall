#!/usr/bin/env node
/**
 * Generates supabase/migrations/0002_seed_tiles.sql — one row per tile in the
 * VI silhouette. The silhouette maths here MUST match lib/vi-mask.ts. A unit
 * test (tests/tiles-seed.test.ts) asserts the two stay in sync so they can
 * never silently drift.
 *
 * Re-run this (npm run gen:tiles) only if you change the wall resolution or
 * the silhouette shape, then re-run the migration on your database.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const GRID_COLS = Number.parseInt(process.env.NEXT_PUBLIC_WALL_COLS ?? "132", 10);
const GRID_ASPECT = 0.62;
const GRID_ROWS = Math.round(GRID_COLS * GRID_ASPECT);

function inRange(v, lo, hi) {
  return v >= lo && v <= hi;
}

function isInsideVi(x, y) {
  const vTop = 0.1, vBottom = 0.9;
  if (inRange(y, vTop, vBottom)) {
    const p = (y - vTop) / (vBottom - vTop);
    const half = 0.06;
    const leftCenter = 0.05 + (0.26 - 0.05) * p;
    const rightCenter = 0.49 + (0.29 - 0.49) * p;
    if (Math.abs(x - leftCenter) < half) return true;
    if (Math.abs(x - rightCenter) < half) return true;
  }
  const iLeft = 0.66, iRight = 0.97, iCenter = (iLeft + iRight) / 2;
  const iTop = 0.1, iBottom = 0.9;
  if (inRange(x, iLeft, iRight) && inRange(y, iTop, iBottom)) {
    if (Math.abs(x - iCenter) < 0.05) return true;
    if (inRange(y, iTop, iTop + 0.12)) return true;
    if (inRange(y, iBottom - 0.12, iBottom)) return true;
  }
  return false;
}

function hash2d(col, row) {
  let h = (col * 73856093) ^ (row * 19349663);
  h = Math.imul(h ^ (h >>> 15), 2246822519);
  h ^= h >>> 13;
  h = Math.imul(h, 3266489917);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
}

export function buildTiles() {
  const raw = [];
  for (let row = 0; row < GRID_ROWS; row++) {
    for (let col = 0; col < GRID_COLS; col++) {
      const nx = (col + 0.5) / GRID_COLS;
      const ny = (row + 0.5) / GRID_ROWS;
      if (isInsideVi(nx, ny)) raw.push({ col, row });
    }
  }
  const withIndex = raw.map((t, index) => ({ ...t, index }));
  const scattered = withIndex
    .map((t) => ({ index: t.index, key: hash2d(t.col, t.row) }))
    .sort((a, b) => a.key - b.key);
  const alloc = new Map();
  scattered.forEach((s, rank) => alloc.set(s.index, rank));
  return withIndex.map((t) => ({
    tile_index: t.index,
    x_position: t.col,
    y_position: t.row,
    allocation_order: alloc.get(t.index),
  }));
}

function main() {
  const tiles = buildTiles();
  const header = `-- ============================================================================
-- The VI Wall — tile seed (auto-generated by scripts/generate-tiles-sql.mjs)
-- Resolution: ${GRID_COLS} x ${GRID_ROWS}  |  capacity: ${tiles.length} tiles
-- Do not edit by hand. Re-run \`npm run gen:tiles\` to regenerate.
-- ============================================================================

truncate table wall_tiles restart identity cascade;

insert into wall_tiles (tile_index, x_position, y_position, allocation_order) values
`;
  const values = tiles
    .map((t) => `(${t.tile_index},${t.x_position},${t.y_position},${t.allocation_order})`)
    .join(",\n");
  const sql = header + values + "\non conflict (tile_index) do nothing;\n";

  const here = dirname(fileURLToPath(import.meta.url));
  const out = join(here, "..", "supabase", "migrations", "0002_seed_tiles.sql");
  writeFileSync(out, sql);
  console.log(`Wrote ${tiles.length} tiles to ${out}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main();
}
